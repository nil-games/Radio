namespace Radio.World
{
    /// <summary>
    /// Что-то идёт прямо сейчас, и сохраниться посреди этого нельзя: звонит телефон,
    /// идёт сон, мини-игра, глюк коридора. Автосохранение ждёт, пока все такие объекты
    /// отпустят (<see cref="AutoSaver"/>).
    /// </summary>
    /// <remarks>
    /// Сохранение не умеет восстанавливать середину события — только то, что уже
    /// случилось или ещё не начиналось. Поэтому проще не сохраняться посреди.
    /// </remarks>
    public interface ISaveBlocker
    {
        bool BlocksSave { get; }
    }
}
